/**
 * Las cinco superficies anatómicas dentales estándar.
 */
export enum TipoSuperficie {
  /** Cara externa orientada hacia los labios o mejillas */
  VESTIBULAR = 'VESTIBULAR',
  /** Cara interna orientada hacia el paladar (superior) o lengua (inferior) */
  PALATINA_LINGUAL = 'PALATINA_LINGUAL',
  /** Cara proximal orientada hacia la línea media dental */
  MESIAL = 'MESIAL',
  /** Cara proximal orientada en sentido opuesto a la línea media dental */
  DISTAL = 'DISTAL',
  /** Cara triturante oclusal (premolares/molares) o borde incisal (incisivos/caninos) */
  OCLUSAL_INCISAL = 'OCLUSAL_INCISAL',
}
